"""
HISTORICAL v1 PROTOTYPE. NOT the generator that produced the released AnomalyThink corpus.

This is the first Real-IAD adaptation of generate_mmad_traces.py: one image per sample,
no red-mask overlay, no reference normal, and the early inspector_prompt.txt. Every
shipped corpus (6K, 15K, GRPO split) was generated by realiad_v4/generate_realiad_traces_v4.py,
which sends three images per anomalous sample (query, red-mask overlay, reference normal) and
loads prompts/inspector_prompt_test_v2.txt. Use that one. This file is kept for provenance only.
"""
